// 职责：验证真实 Vue 页面与纯 Go 服务、真实 WebGL 库联动；使用：先启动 verify-server 与 Vite；边界：环境入库/剪贴板为内存夹具，不证明 Windows 或游戏内验收。
import {createRequire} from 'node:module'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import path from 'node:path'
import os from 'node:os'
const require=createRequire(import.meta.url)
const {chromium}=require(process.env.DSBOX_PLAYWRIGHT_MODULE || 'playwright')
const directory=process.env.DSBOX_QA_DIR || await fs.mkdtemp(path.join(os.tmpdir(),'dsbox-ui-qa-'))
await fs.mkdir(directory,{recursive:true})
const browser=await chromium.launch({headless:true,...(process.env.DSBOX_CHROME_PATH?{executablePath:process.env.DSBOX_CHROME_PATH}:{})})
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}})
 const errors=[];page.on('pageerror',error=>errors.push(error.message))
 await page.goto('http://127.0.0.1:5173/verification/factory/index.html')
 await page.getByRole('button',{name:'计算产线',exact:true}).click()
 await page.getByText('9 台制造设备',{exact:true}).waitFor()
 await page.getByRole('button',{name:'导出方案 JSON',exact:true}).click()
 await page.waitForFunction(()=>Boolean(window.fixture.workspaceJSON))
 const workspace=JSON.parse(await page.evaluate(()=>window.fixture.workspaceJSON))
 assert.equal(workspace.formatVersion,1)
 assert.equal(workspace.plan.machineCount,9)
 assert.equal(workspace.request.targets[0].ratePerMinute,60)
 await page.getByRole('button',{name:'生成蓝图',exact:true}).click()
 await page.getByText('预览就绪',{exact:true}).waitFor()
 assert.equal(await page.locator('canvas').count(),1)
 await page.evaluate(()=>{
  const proto=window.DSPBlueprintEditor.BlueprintViewer.prototype
  const original=proto.selectBuilding
  proto.selectBuilding=function(index){window.qaViewer=this;window.qaIndex=index;return original.call(this,index)}
  const load=proto.loadBlueprint;window.qaLoads=0
  proto.loadBlueprint=function(code){window.qaLoads++;return load.call(this,code)}
 })
 await page.locator('.result-table tbody tr').first().locator('td.numeric').first().click()
 assert.equal(await page.evaluate(()=>window.qaViewer.blueprintData.buildings[window.qaIndex].recipeId),1)
 const before=await page.evaluate(()=>window.qaViewer.camera.position.toArray())
 await page.evaluate(()=>window.qaViewer.selectBuilding(0))
 assert.deepEqual(await page.evaluate(()=>window.qaViewer.camera.position.toArray()),before)
 const reverseIndex=await page.evaluate(()=>window.qaViewer.blueprintData.buildings.findIndex(value=>value.recipeId===9))
 assert.ok(reverseIndex>=0)
 await page.evaluate(index=>window.qaViewer.callbacks.onBuildingSelect(index),reverseIndex)
 assert.ok((await page.locator('tr.selected').innerText()).includes('电磁矩阵'))
 await page.evaluate(()=>window.fixture.toggleTheme())
 await page.waitForFunction(()=>document.documentElement.dataset.theme==='dark')
 await page.screenshot({path:path.join(directory,'wide-dark.png'),fullPage:true})
 await page.evaluate(()=>window.fixture.toggleTheme())
 await page.waitForFunction(()=>document.documentElement.dataset.theme==='light')
 await page.getByRole('button',{name:'复制',exact:true}).click()
 assert.ok((await page.evaluate(()=>window.fixture.copied)).startsWith('BLUEPRINT:'))
 await page.getByRole('button',{name:'存入蓝图库',exact:true}).click()
 assert.equal(await page.evaluate(()=>window.fixture.saved===window.fixture.copied),true)
 const rate=page.locator('.target-rate input')
 await rate.fill('120');await rate.press('Tab')
 await page.getByText('参数已改变，请重新计算',{exact:true}).waitFor()
 await page.getByRole('button',{name:'复制',exact:true}).click()
 await page.getByText('导出上次结果',{exact:true}).first().waitFor()
 await page.getByRole('button',{name:'取消',exact:true}).click()
 await page.getByRole('button',{name:'计算产线',exact:true}).click()
 await page.getByText('17 台制造设备',{exact:true}).waitFor()
 await page.getByRole('button',{name:'生成蓝图',exact:true}).click()
 await page.getByText('预览就绪',{exact:true}).waitFor()
 // 连续重建模型，检查 renderer.info 的几何和纹理数量没有逐次增长。
 const memory=[]
 for(let i=0;i<50;i++) {
  const previous=await page.evaluate(()=>window.qaLoads)
  await page.getByRole('button',{name:'生成蓝图',exact:true}).click()
  await page.waitForFunction(value=>window.qaLoads>value,previous)
  await page.getByText('预览就绪',{exact:true}).waitFor()
  await page.locator('.result-table tbody tr').first().locator('td.numeric').first().click()
  memory.push(await page.evaluate(()=>({...window.qaViewer.renderer.info.memory})))
  if((i+1)%10===0)console.log(`verified ${i+1} actual model reloads`)
 }
 assert.ok(Math.max(...memory.map(value=>value.geometries))-Math.min(...memory.map(value=>value.geometries))<=2)
 assert.ok(Math.max(...memory.map(value=>value.textures))-Math.min(...memory.map(value=>value.textures))<=1)
 await page.screenshot({path:path.join(directory,'wide-light.png'),fullPage:true})
 await page.setViewportSize({width:820,height:900})
 await page.getByText('蓝图预览',{exact:true}).waitFor()
 await page.waitForFunction(()=>{const panel=document.querySelector('.n-drawer');return panel&&panel.getBoundingClientRect().left<100})
 assert.equal(await page.locator('canvas').count(),1)
 await page.screenshot({path:path.join(directory,'narrow-light.png')})
 await page.locator('.n-drawer-header__close').click()
 await page.waitForFunction(()=>document.querySelectorAll('canvas').length===0)
 await page.evaluate(()=>window.fixture.navigate('/away'))
 await page.getByText('缓存页外',{exact:true}).waitFor()
 await page.evaluate(()=>window.fixture.navigate('/dysonSphere/blueprint-generator'))
 await page.getByRole('button',{name:'导入反算',exact:true}).click()
 await page.locator('textarea').fill(await page.evaluate(()=>window.fixture.saved))
 await page.getByRole('button',{name:'严格解析并预览',exact:true}).click()
 await page.getByText('导入的蓝图 · 只读回放',{exact:true}).waitFor()
 await page.getByText('转为量化目标',{exact:true}).waitFor()
 await page.evaluate(async()=>{await document.fonts.ready})
 assert.equal(await page.evaluate(()=>document.fonts.check('14px "JetBrains Mono"')),true)
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
 assert.deepEqual(errors,[])
 console.log(JSON.stringify({passed:true,loads:50,memoryFirst:memory[0],memoryLast:memory.at(-1),directory,errors}))
} finally {await browser.close()}
