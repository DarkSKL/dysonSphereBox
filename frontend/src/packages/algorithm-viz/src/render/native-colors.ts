/**
 * 游戏原生材质颜色表（线性空间 0..1，预览器同样直接按线性值使用）：键为 glTF 材质名。
 *
 * 模型贴图里的底色是灰度，游戏中的橙 / 蓝 / 绿等色相来自材质的 _Color（运行时与贴图相乘），GLB 导出时没有带上。
 * 本表由游戏材质数据按材质名对照生成，只包含机身材质；玻璃、特效、遮罩等材质由渲染器按类别处理。
 * emissive 为带色相的自发光遮罩颜色，缺省表示遮罩无色。
 */
export interface NativeMaterialColor {
  readonly color: readonly [number, number, number];
  readonly emissive?: readonly [number, number, number];
  /** 涂装遮罩编号，对应 data/models/masks/mask-<编号>.png；缺省表示整个分组都染色 */
  readonly mask?: string;
  /** 自发光依赖供电：游戏中未供电时关闭，预览器同样不发光 */
  readonly unlit?: boolean;
}

