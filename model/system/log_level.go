package system

// 文件职责：定义系统日志的重要等级枚举。
// 使用：helper/system 记录日志和 service/system 查询日志时引用，用于筛选与展示严重程度。
// 边界：只表达展示和筛选等级，不决定业务是否回滚或是否重试。

// LogLevel 表示系统日志的重要等级。
// 职责：定义系统日志严重程度枚举。
// 使用：业务记录日志时按影响范围选择等级，查询端可按等级过滤重要操作。
// 边界：只表达展示和筛选等级，不决定业务是否回滚。
type LogLevel int

// 日志等级常量职责：定义当前系统日志支持的稳定等级。
// 使用：helper 记录日志和前端筛选日志时使用。
// 边界：新增等级需要同步前端展示文案和筛选控件。
const (
	// LogLevelDebug 表示调试信息，默认不用于关键业务审计。
	// 职责：标记调试级诊断信息。
	// 使用：开发或排查问题时记录低影响信息。
	// 边界：不应用于用户必须关注的失败或警告。
	LogLevelDebug LogLevel = 10
	// LogLevelInfo 表示普通操作信息。
	// 职责：标记正常完成的普通操作。
	// 使用：安装成功、配置保存、状态变化等常规事件。
	// 边界：不表示异常或需要用户介入。
	LogLevelInfo LogLevel = 20
	// LogLevelWarn 表示需要关注但未阻断流程的异常状态。
	// 职责：标记未阻断但需要关注的状态。
	// 使用：环境未就绪、部分步骤跳过等场景。
	// 边界：不表示操作彻底失败。
	LogLevelWarn LogLevel = 30
	// LogLevelError 表示操作失败或需要用户介入的错误。
	// 职责：标记失败或需要用户处理的错误事件。
	// 使用：安装失败、更新失败、配置写入失败等场景。
	// 边界：记录错误不等于自动恢复，恢复策略由业务流程决定。
	LogLevelError LogLevel = 40
)
