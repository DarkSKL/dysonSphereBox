import "errors"

// ErrInstallCancelled 表示文件复制过程被上层安装上下文取消。
// 职责：提供文件复制、下载和安装流程共用的取消哨兵错误。
// 使用：复制器、下载器和安装器用 errors.Is 判断用户取消，服务层据此展示“已取消”而不是普通失败。
// 边界：该错误只描述主动取消，不代表网络、磁盘或权限故障。
var ErrInstallCancelled = errors.New("安装已取消")

