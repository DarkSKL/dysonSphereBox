// CandidateVeinTypes 职责：列出主题可能包含的矿种；使用：矿点精化前筛选；边界：不涉及数量、存在性或坐标。
func CandidateVeinTypes(planet Planet, star Star, theme SurfaceTheme) []int {
	profile, ok := vanillaVeins[theme.ID]
	if !ok {
		return nil
	}
	var candidates [15]bool
	for i, spots := range profile.spots {
		candidates[i+1] = spots > 0
	}
	for _, rare := range profile.rare {
		if planet.StarID == 1 && rare.birthOdds > 0 || planet.StarID > 1 && rare.odds > 0 {
			candidates[rare.kind] = true
		}
	}
	switch star.Kind {
	case 2:
		candidates[9], candidates[10], candidates[12] = true, true, true
	case 3, 4:
		candidates[14] = true
	}
	out := make([]int, 0, len(candidates))
	for kind, possible := range candidates {
		if possible {
			out = append(out, kind)
		}
	}
	return out
}
